"""Build low-res cover thumbnails and the cover list for page.htm.

For every PDF in ./pdfs this renders page 1 to ./thumbnails/<same name>.jpg
and writes ./thumbnails/covers.js, which page.htm loads.

Re-run it after adding or removing PDFs:
    python make_thumbnails.py           (skips thumbnails that already exist)
    python make_thumbnails.py --force   (re-renders everything)

Requires: pip install pymupdf pillow
"""
import io
import json
import os
import sys

import pymupdf
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PDF_DIR = os.path.join(HERE, "pdfs")
THUMB_DIR = os.path.join(HERE, "thumbnails")

# iPad 1 screen is 1024x768 (non-retina); covers are drawn at most ~340px tall.
THUMB_HEIGHT = 340
MAX_WIDTH = 340
JPEG_QUALITY = 72


def render_first_page(pdf_path, jpg_path):
    doc = pymupdf.open(pdf_path)
    try:
        page = doc[0]
        rect = page.rect
        zoom = min(THUMB_HEIGHT / rect.height, MAX_WIDTH / rect.width) * 2  # 2x then downsample
        pix = page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), alpha=False)
        img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")
    finally:
        doc.close()
    scale = min(THUMB_HEIGHT / float(img.height), MAX_WIDTH / float(img.width))
    size = (max(1, int(round(img.width * scale))), max(1, int(round(img.height * scale))))
    img = img.resize(size, Image.LANCZOS)
    # baseline (non-progressive) JPEG: decodes cheapest on old iOS devices
    img.save(jpg_path, "JPEG", quality=JPEG_QUALITY, optimize=True, progressive=False)
    return size


def main():
    force = "--force" in sys.argv
    if not os.path.isdir(THUMB_DIR):
        os.makedirs(THUMB_DIR)

    pdfs = sorted((f for f in os.listdir(PDF_DIR) if f.lower().endswith(".pdf")),
                  key=lambda s: s.lower())
    covers = []
    failed = []
    for i, name in enumerate(pdfs):
        base = name[:-4]
        jpg_name = base + ".jpg"
        jpg_path = os.path.join(THUMB_DIR, jpg_name)
        try:
            if force or not os.path.exists(jpg_path):
                w, h = render_first_page(os.path.join(PDF_DIR, name), jpg_path)
                print("[%d/%d] %s (%dx%d)" % (i + 1, len(pdfs), jpg_name, w, h))
            else:
                with Image.open(jpg_path) as im:
                    w, h = im.size
        except Exception as e:  # unreadable PDF: list it without a picture
            print("[%d/%d] FAILED %s: %s" % (i + 1, len(pdfs), name, e))
            failed.append(name)
            jpg_name, w, h = "", 255, 340
        covers.append([name, jpg_name, w, h])

    with open(os.path.join(THUMB_DIR, "covers.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by make_thumbnails.py: [pdf file, thumbnail file, width, height] */\n")
        f.write("var COVERS = [\n")
        f.write(",\n".join(json.dumps(c, ensure_ascii=True) for c in covers))
        f.write("\n];\n")

    print("\n%d covers written to thumbnails/covers.js" % len(covers))
    if failed:
        print("%d PDFs could not be rendered:" % len(failed))
        for n in failed:
            print("  " + n)


if __name__ == "__main__":
    main()
